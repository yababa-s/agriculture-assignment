"""Write docs/demo_queries.md: the 10 live demo questions with the expected answer, tool, SQL and citations.

Run after any change to the database: python scripts/make_demo_doc.py
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from agri import config  # noqa: E402
from agri.query.agent import QueryAgent  # noqa: E402


def main() -> None:
    demo = json.loads((config.ROOT / "data" / "gold" / "demo_queries.json").read_text())
    ag = QueryAgent(config.DB_PATH, planner="rules")
    out = ["# Live demonstration: 10 queries with expected answers", "",
           f"Generated by `scripts/make_demo_doc.py` from `{config.DB_PATH.name}` with the rule planner. "
           "Coverage: " + ", ".join(f"{t} ×{sum(d['type'] == t for d in demo)}" for t in sorted({d['type'] for d in demo})) + ".",
           "Run them live with `python scripts/ask.py --demo` (model planner) or `--no-llm` (rules); "
           "add `--show-source` to open the cited page with the cell highlighted.", ""]
    for d in demo:
        a = ag.ask(d["question"])
        out += [f"## {d['id']} ({d['type']}): {d['question']}", "", f"Tool `{a.tool}` · arguments `{json.dumps(a.args, ensure_ascii=False, default=str)}`", "",
                "```text", a.text, "```", ""]
        if a.citations:
            c = a.citations[0]
            out += [f"Top citation: **{c['document_id']}** `{c['file_name']}`, page {c['page']}, table `{c['table']}`, "
                    f"row \"{c['row']}\", column \"{c['column']}\", printed `{c['printed']}`.", ""]
    (config.ROOT / "docs" / "demo_queries.md").write_text("\n".join(out))
    print("-> docs/demo_queries.md")


if __name__ == "__main__":
    main()
