"""Compose docs/evaluation.md from eval/results/*.json (so reported numbers always match measured ones)."""
from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from agri import config  # noqa: E402

ACCEPT = {
    "value_checks": 0.95, "groundedness": 0.99, "routing_manifest": 1.0, "routing_llm": 0.8,
    "island_f1_gated": 0.8, "column_accuracy": 0.8, "json_valid": 0.95, "automation": 0.9,
}


def load(name: str):
    p = config.RESULTS_DIR / name
    return json.loads(p.read_text()) if p.exists() else None


def pf(x, target):
    return "✅" if x is not None and x >= target else "❌"


def llm_table(base, ada) -> str:
    rows = []

    def g(d, *path):
        for k in path:
            d = (d or {}).get(k)
        return d
    spec = [
        ("Island extraction: JSON valid rate", ("island_extraction", "json_valid_rate"), ACCEPT["json_valid"]),
        ("Island extraction: replies recovered by salvage parser (loops / bad literals)", ("island_extraction", "json_salvaged_rate"), None),
        ("Island extraction: catalogue adherence (valid metric ids)", ("island_extraction", "catalogue_adherence"), None),
        ("Island extraction: groundedness (evidence verbatim + contains value)", ("island_extraction", "groundedness_rate"), None),
        ("Island extraction: precision (raw)", ("island_extraction", "raw", "precision"), None),
        ("Island extraction: recall (raw)", ("island_extraction", "raw", "recall"), None),
        ("Island extraction: F1 (raw)", ("island_extraction", "raw", "f1"), None),
        ("Island extraction: F1 after groundedness gate", ("island_extraction", "after_groundedness_gate", "f1"), ACCEPT["island_f1_gated"]),
        ("Column mapping: JSON valid rate", ("column_mapping", "json_valid_rate"), ACCEPT["json_valid"]),
        ("Column mapping: column accuracy (location+metric+period)", ("column_mapping", "column_accuracy"), ACCEPT["column_accuracy"]),
        ("Column mapping: location accuracy", ("column_mapping", "location_accuracy"), None),
        ("Column mapping: metric accuracy", ("column_mapping", "metric_accuracy"), None),
        ("Column mapping: period accuracy", ("column_mapping", "period_accuracy"), None),
        ("Routing, model only (manifest hidden): accuracy over 20 files", ("routing", "accuracy"), None),
        ("Routing, model on the files the fingerprint finds ambiguous", ("routing", "model_accuracy_on_ambiguous"), None),
        ("Routing, deployed hybrid (fingerprint rules + model when ambiguous)", ("routing", "hybrid_accuracy"), ACCEPT["routing_llm"]),
        ("Routing: valid agent id rate", ("routing", "valid_agent_id_rate"), None),
        ("Median latency per island (s)", ("island_extraction", "latency_s_median"), None),
    ]
    rows.append("| Metric | Base Qwen2.5-3B (4-bit) | + LoRA adapter | Δ | Target |")
    rows.append("|---|---|---|---|---|")
    for name, path, target in spec:
        b, a = g(base, *path), g(ada, *path)
        d = (a - b) if isinstance(a, (int, float)) and isinstance(b, (int, float)) else None
        tgt = f"≥ {target} {pf(a, target)}" if target is not None else ""
        rows.append(f"| {name} | {b} | {a} | {'' if d is None else f'{d:+.3f}'} | {tgt} |")
    return "\n".join(rows)


def main() -> None:
    base, ada = load("llm_eval_base.json"), load("llm_eval_qlora_v1.json")
    agents = sorted(config.RESULTS_DIR.glob("agent_eval_*.json"), key=lambda p: p.stat().st_mtime)
    ag = json.loads(agents[-1].read_text()) if agents else None
    tools = {t: load(f"tool_comparison_{t}.json") for t in ("pdfplumber", "pymupdf", "docling", "ours")}
    gold_isl = json.loads((config.GOLD_DIR / "island_profiles_D10.json").read_text())
    gold_col = json.loads((config.GOLD_DIR / "column_mapping_eval.json").read_text())
    vc = json.loads((config.GOLD_DIR / "value_checks.json").read_text())

    L = ["# Evaluation\n",
         "All numbers on this page are generated by `scripts/make_eval_report.py` from `eval/results/*.json`.\n",
         "## 1. Evaluation design\n",
         "| Set | Source documents | Size | How the reference was made | Used in training? |",
         "|---|---|---|---|---|",
         f"| Island extraction gold | D10 (2024-25) | {gold_isl['n_islands']} islands, {gold_isl['n_items']} items | rule extractor output checked line by line against page text | **No** |",
         f"| Column-mapping gold | D02, D06 | {gold_col['n_examples']} prompts, {gold_col['n_columns']} columns | rule-resolved specs, D02 checked against rendered page | **No** |",
         "| Routing gold | all 20 files | 20 | manifest source group (human-assigned in Phase 1/2) | No (router not fine-tuned) |",
         f"| Direct value checks | D01, D02, D05, D07, D10, D12, D13, D15, D16, D17 | {len(vc['checks'])} values | read by eye from rendered pages | No |",
         "| LoRA training set | D08, D09 islands; D01, D03, D04, D05 tables | 84 train + 9 valid | rule-labelled (silver) | — |",
         "",
         "Split is by **document** (`data/splits/splits.json`). `scripts/build_datasets.py` asserts that no eval-island text "
         "appears in the training files. D06 (bilingual, non-English), D10 and D13 (raster-ruled) contribute nothing to training "
         "and are used as the unseen-document demo set together with instructor files.\n",
         "**Acceptance criteria (set before running):** "
         + ", ".join(f"{k} ≥ {v}" for k, v in ACCEPT.items()) + ".\n",
         "## 2. With vs without the LoRA adapter (held-out tasks)\n",
         "Model output is scored raw: no teacher fill-in and no retries, so the numbers measure the model itself.\n",
         llm_table(base, ada) if base and ada else "_LLM evaluation results missing: run scripts/eval_llm_tasks.py_",
         ""]
    tp, bp, ap_ = load("llm_eval_teacher.json"), base, ada
    if tp and bp and ap_ and "island_perturbed" in (bp or {}) and "island_perturbed" in (ap_ or {}):
        def row(name, d, key):
            x = d[key]
            return (f"| {name} | {x['raw']['precision']} | {x['raw']['recall']} | {x['raw']['f1']} | "
                    f"{x['after_groundedness_gate']['f1']} | {x['groundedness_rate']} |")
        L += ["### Robustness to an unseen layout (same D10 facts, reworded)\n",
              "Each `Key-Value` pair is rewritten as `value key;` (e.g. `Farmers-6192` → `6192 farmers;`). "
              "None of the three systems saw this surface form; the facts and reference items are unchanged.\n",
              "| System | layout | precision | recall | F1 | F1 after gate | groundedness |", "|---|---|---|---|---|---|---|",
              row("Rule teacher (regex)", tp, "island_extraction").replace("| Rule teacher (regex) |", "| Rule teacher (regex) | original |"),
              row("Rule teacher (regex)", tp, "island_perturbed").replace("| Rule teacher (regex) |", "| Rule teacher (regex) | reworded |"),
              row("Base Qwen2.5-3B", bp, "island_perturbed").replace("| Base Qwen2.5-3B |", "| Base Qwen2.5-3B | reworded |"),
              row("+ LoRA adapter", ap_, "island_perturbed").replace("| + LoRA adapter |", "| + LoRA adapter | reworded |"), ""]
    if base and ada:
        L += ["Per-metric recall on island extraction (base → adapter):\n", "| metric | base | adapter |", "|---|---|---|"]
        pb, pa = base["island_extraction"]["per_metric_recall"], ada["island_extraction"]["per_metric_recall"]
        for m in sorted(set(pb) | set(pa)):
            L.append(f"| {m} | {pb.get(m, '')} | {pa.get(m, '')} |")
        L += ["", "Typical base-model failures on held-out islands (from `examples`):\n", "```json",
              json.dumps(base["island_extraction"]["examples"][:2], indent=1), "```",
              "Column-mapping errors that remain with the adapter:\n", "```json",
              json.dumps(ada["column_mapping"]["errors"][:4], indent=1), "```", ""]
        rr = {r["doc"]: r for r in base["routing"]["rows"]}
        ra = {r["doc"]: r for r in ada["routing"]["rows"]}
        L += ["Routing (model only, manifest hidden):\n", "| doc | expected | base | adapter |", "|---|---|---|---|"]
        for d in sorted(rr):
            L.append(f"| {d} | {rr[d]['expected']} | {rr[d]['predicted']} {'✓' if rr[d]['ok'] else '✗'} | "
                     f"{ra.get(d, {}).get('predicted')} {'✓' if ra.get(d, {}).get('ok') else '✗'} |")
        L.append("")
    ls = load("langsmith_experiments.json")
    if ls:
        L += ["### Recorded in LangSmith\n",
              f"The same held-out sets are uploaded as LangSmith datasets and each model is an experiment ({ls['note']}). "
              f"Pipeline runs are traced to the LangSmith project [`34_AN_agriagent`]({ls.get('trace_project_url', '')}) "
              f"(every graph node, tool call and LLM call; traced batch {ls.get('traced_batch', '')}).\n",
              "| Experiment | Task | Model | Examples | Scores | Link |", "|---|---|---|---|---|---|"]
        for e in ls["experiments"]:
            L.append(f"| {e['experiment']} | {e['task']} | {e['model']} | {e['examples']} | "
                     + ", ".join(f"{k} {v}" for k, v in e["scores"].items()) + f" | [open]({e['url']}) |")
        L.append("")
    if ag:
        w = ag["workflow"]
        L += [f"## 3. Agent and workflow evaluation (batch `{ag['batch_id']}`)\n",
              "Evaluator menu: Microsoft Foundry agent evaluators. Trajectory scoring uses AgentEvals "
              "(`create_trajectory_match_evaluator`, superset mode). Every run is traced locally (`logs/traces`) "
              "and in LangSmith when a key is configured.\n",
              "| Foundry evaluator | Our implementation | Result |", "|---|---|---|",
              f"| Tool Call Accuracy: selection | router decision vs routing gold | {w['routing_accuracy']} |",
              f"| Tool Call Accuracy: trajectory | AgentEvals superset match vs reference tool sequence | see per-agent table |",
              "| Tool Input Accuracy | argument validators on each recorded tool call | see per-document JSON |",
              f"| Task Completion | terminal status loaded=1, partial=0.5 | {w['task_completion_mean']} |",
              f"| Task Adherence | validator acceptance rate | {w['observations_loaded']} loaded / {w['rejected']} rejected |",
              f"| Groundedness | loaded value_raw found on cited page | {w['groundedness_overall']} {pf(w['groundedness_overall'], ACCEPT['groundedness'])} |",
              f"| Task Navigation Efficiency | LLM calls, retries, rejected model outputs, duplicates | {w['automation']['llm_calls']} calls, {w['automation']['retries']} retries, {w['automation']['model_outputs_rejected_by_gates']} rejected outputs |",
              f"| (direct) value checks | 48 hand-read values vs DB | {ag['value_checks']['correct']}/{ag['value_checks']['n']} {pf(ag['value_checks']['accuracy'], ACCEPT['value_checks'])} |",
              "", "**Skipped evaluators and why**\n"]
        L += [f"* **{k}**: {v}" for k, v in ag["evaluators_skipped"].items()]
        L += ["", "### Per agent / source group\n",
              "| agent | group | docs | task completion | trajectory match | task adherence | loaded | LLM calls | model outputs rejected | groundedness |",
              "|---|---|---|---|---|---|---|---|---|---|"]
        grp = {d["agent"]: d["group"] for d in ag["per_document"]}
        for a, pa in sorted(ag["per_agent"].items()):
            gr = ag["groundedness_by_agent"].get(a, {}).get("rate", "n/a")
            L.append(f"| {a} | {grp.get(a, '')} | {int(pa['documents'])} | {pa['task_completion']} | {pa['trajectory_match_rate']} | "
                     f"{pa['task_adherence']} | {int(pa['n_loaded'])} | {int(pa['llm_calls'])} | {int(pa['model_outputs_rejected'])} | {gr} |")
        L += ["", "### Per document\n", "| doc | agent | routed by | status | extracted | loaded | rejected | LLM calls | attempts | errors handled |",
              "|---|---|---|---|---|---|---|---|---|---|"]
        for d in ag["per_document"]:
            eh = ", ".join(sorted({f"{e['error']}→{e['handled_by']}" for e in d["errors_handled"]}))[:160]
            L.append(f"| {d['document_id']} | {d['agent']} | {d['routed_by']} | {d['status']} | {d['n_extracted']} | {d['n_loaded']} | "
                     f"{d['n_rejected']} | {d['llm_calls']} | {d['attempts']} | {eh} |")
        a = w["automation"]
        L += ["", "## 4. Automation\n",
              f"* Inputs completed without manual intervention / inputs attempted: **{a['inputs_completed_without_manual_intervention']}/{a['inputs_attempted']} = {a['automation_rate']}**",
              f"* Manual interventions during the run: {a['manual_interventions_in_run']}",
              f"* Retries triggered by the validator: {a['retries']}; LLM calls: {a['llm_calls']}; model outputs rejected by gates: {a['model_outputs_rejected_by_gates']}; duplicate rows skipped: {a['duplicate_rows_skipped']}",
              f"* Needing review or failed: {a['needs_review_or_failed'] or 'none'}",
              "* Manual steps that remain outside the run, each done once:",
              "  * source discovery and download (Phase 1)",
              "  * copying document URLs into the manifest",
              "  * reviewing gold sets",
              "  * deciding the source group of each corpus file (unseen files are routed automatically)",
              "* Remaining barriers to automation:",
              "  * chart-only atlas pages (D18) need chart digitisation",
              "  * raster maps are out of scope by brief",
              "  * an instructor file with a new price layout would rely on LLM column mapping",
              "  * no robots.txt-aware downloader yet: Phase 1 files were fetched by hand", ""]
    if all(tools.values()):
        L += ["## 5. Tool comparison on the hardest cases\n", "| case | pdfplumber | PyMuPDF | Docling | ours |", "|---|---|---|---|---|"]
        for case in tools["ours"]:
            cells = []
            for t in ("pdfplumber", "pymupdf", "docling", "ours"):
                r = tools[t].get(case, {})
                cells.append("n/a" if "not_applicable" in r else (f"error" if "error" in r else f"{r['correct']}/{r['of']}"))
            L.append(f"| {case} | " + " | ".join(cells) + " |")
        L.append("")
    out = config.ROOT / "docs" / "evaluation.md"
    out.write_text("\n".join(L))
    print(f"-> {out}")


if __name__ == "__main__":
    main()
